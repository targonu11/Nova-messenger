export function filterEmojiShortcodes(query, limit = 8) {
  const q = String(query || '').toLowerCase().replace(/^:/, '').replace(/:$/, '');
  if (!q) {
    return EMOJI_SHORTCODES.slice(0, limit).map(([id, emoji]) => ({ id, emoji }));
  }
  const scored = [];
  for (const [id, emoji] of EMOJI_SHORTCODES) {
    if (id === q) scored.push({ id, emoji, score: 0 });
    else if (id.startsWith(q)) scored.push({ id, emoji, score: 1 });
    else if (id.includes(q)) scored.push({ id, emoji, score: 2 });
  }
  scored.sort((a, b) => a.score - b.score || a.id.localeCompare(b.id));
  return scored.slice(0, limit).map(({ id, emoji }) => ({ id, emoji }));
}

export function getEmojiQuery(text) {
  const m = String(text || '').match(/(?:^|[\s(]):([a-zA-Z0-9_+-]*)$/);
  return m ? m[1] : null;
}

export function insertEmojiShortcode(text, emoji) {
  const src = String(text || '');
  const re = /:([a-zA-Z0-9_+-]*)$/;
  if (re.test(src)) return src.replace(re, `${emoji} `);
  return `${src}${emoji} `;
}
